"""Benchmarks: fixed tasks that mini runs on a model (a preset) to build a baseline of what that model can do.

A task is a prompt (and sometimes a follow-up prompt, run in the same folder with the tools from the first one), the
files of the folder it starts in, and a check: a standard-library Python script `check.py WORKDIR TRANSCRIPT` that
exits 0 when the result is right. Fixtures and checks are generated by the suite modules (bench/suites/*.py) from
fixed seeds, so every run of a task sees the same files and the same expected answer.

Suites, easiest first:
  core     everyday work in a folder: a CSV report, a list, a code fix, a rename, a log question, a flag
  formats  undocumented binary and compressed formats, a folder inventory
  calc     arithmetic that must be done by a program (checked: every number came from program output)
  tools    building tools with third-party libraries (PDF, XLSX, QR, images, YAML/TOML, mail) and reusing them
  hard     rule-heavy data work: bank reconciliation, logs across a DST change, a build-order tool to upgrade
  expert   harder still: a bug hunt across a package, a calendar scheduling puzzle, FIFO stock accounting

Results (bench/results.py) are one row per run of a task: passed or failed, and how long it ran.
"""
import importlib
import textwrap

SUITES = ("core", "formats", "calc", "tools", "hard", "expert")
DEFAULT_TIMEOUT = 1500


class Task:
    def __init__(self, suite, name, prompt, files, check, prompt2=None, setup=None, timeout=DEFAULT_TIMEOUT,
                 needs=None):
        self.suite, self.name, self.prompt, self.files, self.check = suite, name, prompt, files, check
        self.prompt2, self.setup, self.timeout, self.needs = prompt2, setup, timeout, needs or []

    def summary(self):
        return " ".join(self.prompt.split())[:110]


class Suite:
    """What a suite module fills: Suite.add() takes the task as the old bench2 generators wrote it."""

    def __init__(self, name):
        self.name, self.tasks = name, {}

    def add(self, name, prompt, files, check, prompt2=None, setup=None, timeout=DEFAULT_TIMEOUT, needs=None):
        self.tasks[name] = Task(self.name, name, prompt, files, check, prompt2,
                                textwrap.dedent(setup).lstrip() if setup else None, timeout, needs)


_loaded = {}


def suite(name):
    """The tasks of one suite (generated on first use: some suites build images, PDFs or databases)."""
    if name not in SUITES:
        raise KeyError(f"no suite {name!r}; suites: {', '.join(SUITES)}")
    if name not in _loaded:
        _loaded[name] = importlib.import_module(f".suites.{name}", __name__).SUITE
    return _loaded[name]


def tasks(names=None, suites=None):
    """Tasks in suite order: the ones named (task or suite names), else every task of the suites given, else all."""
    out = {}
    for s in SUITES:
        for t in suite(s).tasks.values():
            out[t.name] = t
    if not names and not suites:
        return list(out.values())
    want = []
    for n in list(suites or []) + list(names or []):
        if n in SUITES:
            want += [t for t in out.values() if t.suite == n]
        elif n in out:
            want.append(out[n])
        else:
            raise KeyError(f"no task or suite {n!r}")
    return list({t.name: t for t in want}.values())
